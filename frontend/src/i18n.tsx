export function getLanguage(): Language { return currentLanguage; }
export function t(value: string): string {
  if (currentLanguage === 'en' || !value) return value;
  const leading = value.match(/^\s*/)?.[0] ?? '';
  const trailing = value.match(/\s*$/)?.[0] ?? '';
  const key = value.trim();
  const onlineCount = key.match(/^(\d+) online now$/);
  if (onlineCount) return `${leading}${Number(onlineCount[1]).toLocaleString('fa-IR')} دوربین آنلاین${trailing}`;
  const processedCount = key.match(/^(\d+) processed$/);
  if (processedCount) return `${leading}${Number(processedCount[1]).toLocaleString('fa-IR')} پردازش‌شده${trailing}`;
  const translated = fa[key];
  if (translated) return `${leading}${translated}${trailing}`;
  const runMatch = key.match(/^Run #(\d+) is waiting for the backend worker\.$/);
  if (runMatch) return `${leading}اجرای شماره ${runMatch[1]} در انتظار Worker بک‌اند است.${trailing}`;
  const savedMatch = key.match(/^(.+) is saved to this workspace\.$/);
  if (savedMatch) return `${leading}${savedMatch[1]} در این فضای کاری ذخیره شد.${trailing}`;
  const teamDescription = key.match(/^Manage the people and roles for (.+)\.$/);
  if (teamDescription) return `${leading}افراد و نقش‌های سازمان ${teamDescription[1]} را مدیریت کنید.${trailing}`;
  const analysisRun = key.match(/^Analysis run #(\d+)$/);
  if (analysisRun) return `${leading}اجرای تحلیل شماره ${analysisRun[1]}${trailing}`;
  const frameCount = key.match(/^(\d+) frames contain visual analysis output$/);
  if (frameCount) return `${leading}${frameCount[1]} فریم دارای خروجی تحلیل تصویری هستند${trailing}`;
  const disableMatch = key.match(/^Disable camera “(.+)”\? The record will be retained\.$/);
  if (disableMatch) return `${leading}دوربین «${disableMatch[1]}» غیرفعال شود؟ اطلاعات آن حفظ خواهد شد.${trailing}`;
  const overviewMatch = key.match(/^Here’s the latest operational picture for (.+)\.$/);
  if (overviewMatch) return `${leading}آخرین وضعیت عملیاتی ${overviewMatch[1]} به این صورت است.${trailing}`;
  const invitedMatch = key.match(/^(.+) has been invited as (owner|admin|operator|analyst|viewer)\.$/);
  if (invitedMatch) {
    const role = fa[invitedMatch[2][0].toUpperCase() + invitedMatch[2].slice(1)] || invitedMatch[2];
    return `${leading}${invitedMatch[1]} با نقش ${role} دعوت شده است.${trailing}`;
  }
  const readyMatch = key.match(/^(.+) is ready\.$/);
  if (readyMatch) return `${leading}${readyMatch[1]} آماده است.${trailing}`;
  const removeMemberMatch = key.match(/^Remove (.+) from (.+)\?$/);
  if (removeMemberMatch) return `${leading}عضویت ${removeMemberMatch[1]} از سازمان ${removeMemberMatch[2]} حذف شود؟${trailing}`;
  return value;
}

export function setLanguage(language: Language) {
  if (language === currentLanguage) return;
  currentLanguage = language;
  if (typeof window !== 'undefined') { try { window.localStorage.setItem(STORAGE_KEY, language); } catch { /* Storage may be disabled by browser policy. */ } }
  listeners.forEach((listener) => listener());
}

function subscribe(listener: () => void) { listeners.add(listener); return () => listeners.delete(listener); }
function getSnapshot() { return currentLanguage; }

export function useLanguage() {
  const language = useSyncExternalStore(subscribe, getSnapshot, getSnapshot);
  return { language, direction: language === 'fa' ? 'rtl' as const : 'ltr' as const, setLanguage };
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const { language, direction } = useLanguage();
  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dir = direction;
    document.documentElement.dataset.language = language;
    document.title = language === 'fa' ? 'AEGISVISION — هوشمندی ویدئویی' : 'AEGISVISION — Video Intelligence';
  }, [language, direction]);
  return createElement('div', { className: 'language-root' }, children);
}

export function LanguageSwitcher({ className = '' }: { className?: string }) {
  const { language, setLanguage } = useLanguage();
  return <div className={`language-switcher ${className}`} role="group" aria-label={t('Language')}>
    <button type="button" className={language === 'en' ? 'active' : ''} onClick={() => setLanguage('en')} aria-pressed={language === 'en'}>English</button>
    <button type="button" className={language === 'fa' ? 'active' : ''} onClick={() => setLanguage('fa')} aria-pressed={language === 'fa'}>فارسی</button>
  </div>;
}
